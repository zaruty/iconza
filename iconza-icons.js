/**
 * Renderiza um ícone SVG inline
 * @param {string} name - Nome do ícone
 * @param {object} opts - { size, stroke, className }
 * @returns {string} HTML do SVG
 */
window.icon = function(name, opts = {}) {
  const {
    size = 18,
    stroke = 1.5,
    className = '',
    color = 'currentColor'
  } = opts;

  const path = window.IconzaIcons[name];
  if (!path) {
    console.warn(`Icon "${name}" not found`);
    return '';
  }

  return `<svg
    width="${size}"
    height="${size}"
    viewBox="0 0 24 24"
    fill="none"
    stroke="${color}"
    stroke-width="${stroke}"
    stroke-linecap="round"
    stroke-linejoin="round"
    ${className ? `class="${className}"` : ''}
  >${path}</svg>`;
};

/**
 * Cria um elemento DOM com o ícone
 * @param {string} name
 * @param {object} opts
 * @returns {HTMLElement}
 */
window.createIcon = function(name, opts = {}) {
  const wrapper = document.createElement('span');
  wrapper.style.display = 'inline-flex';
  wrapper.innerHTML = window.icon(name, opts);
  return wrapper.firstElementChild;
};
